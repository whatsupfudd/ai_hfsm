-- | A complete Store IO implementation over the CT-02 schema.
-- The CT-01 Store interface does not expose errors for read/claim operations.
-- Such errors are therefore raised as IO exceptions rather than suppressed.
postgresStore :: Runner -> Store IO
postgresStore runner =  postgresStoreScoped Nothing runner


postgresStoreForInstance :: Runner -> UUID -> Store IO
postgresStoreForInstance runner instanceId = postgresStoreScoped (Just instanceId) runner


postgresStoreScoped :: Maybe UUID -> Runner -> Store IO
postgresStoreScoped instanceFilter runner =
  Store
  { leaseSignal = \rq -> do
      let n = fromIntegral (max 1 (min 100 rq.batchSize)) :: Int32
          secs = fromIntegral (max 1 (min 3600 rq.leaseSeconds)) :: Int32
      vals <- require runner (writeTx (X.claimSignalsTx n rq.node secs instanceFilter))
      rows <- requireDecoded (traverse decodeValue (V.toList vals))
      pure (if null rows then LeaseNoneLz else LeaseSomeLz rows)
  , loadInstance = \i -> do
      mv <- require runner (Hs.statement i S.loadInstance)
      traverse (requireDecoded . decodeValue) mv
  , loadSnapshot = \s -> do
      mv <- require runner (Hs.statement s S.loadSnapshot)
      traverse (requireDecoded . decodeValue) mv
  , commitTurn = \rq -> execute runner (writeTx (X.commitTurnTx rq))
  , ackSignal = \rq -> execute runner (writeTx (X.ackFailureTx rq))
  , renewLease = \rq -> execute runner (writeTx (X.renewLeaseTx rq))
  , listSignals = \rq -> do
      let states = V.fromList (map signalStatusSql rq.status)
          limit = fromIntegral (max 0 (min 10000 rq.limit)) :: Int32
      vals <- require runner (Hs.statement (states,limit) S.listSignals)
      requireDecoded (traverse decodeValue (V.toList vals))
  }

-- | Releases must be registered before instance initialization. Haskell
-- closures are NOT stored in PostgreSQL; only machine identity is retained.
registerMachine :: Runner -> MachineKey -> IO (Either StoreErr ())
registerMachine runner key = execute runner (writeTx (X.registerReleaseTx key >> pure (Right ())))

-- | Two-row atomic insert using a deferred FK for the revision-zero snapshot.
initializeInstance :: Runner -> NewInstance -> IO (Either StoreErr UUID)
initializeInstance runner new = execute runner (writeTx (X.createInstanceTx new))

-- | An enqueue is ordered under an instance lock and idempotent when dedupeKey
-- is supplied. The request's UUID must be freshly generated by the caller.
enqueue :: Runner -> EnqueueRq -> IO (Either StoreErr UUID)
enqueue runner rq = execute runner (writeTx (X.enqueueTx rq))

-- | No blind internal retries of commitTurn; in particular a state/planner
-- conflict must be surfaced to the worker. Hasql's transactionNoRetry ensures
-- this Tx isn't implicitly re-executed after SQLSTATE failures.
writeTx :: Tx.Transaction a -> Hs.Session a
writeTx = TS.transactionNoRetry TS.ReadCommitted TS.Write

execute :: Runner -> Hs.Session (Either StoreErr a) -> IO (Either StoreErr a)
execute runner session = do
  result <- (Pt.runSession runner) session
  pure $ case result of
    Left err -> Left (classify err)
    Right value -> value

require :: Runner -> Hs.Session a -> IO a
require runner session = do
  result <- (Pt.runSession runner) session
  case result of
    -- Left err -> throwIO (userError (T.unpack (E.toMessage err)))
    Left err -> throwIO (userError (show err))
    Right value -> pure value

requireDecoded :: Either StoreErr a -> IO a
requireDecoded = either (throwIO . userError . show) pure

-- classify :: E.SessionError -> StoreErr
classify :: Hp.UsageError -> StoreErr
classify err =
  let
    -- message = E.toMessage err
    topMsg = T.pack $ show err
  in
  case err of
    Hp.SessionUsageError sessErr -> 
      -- case E.toSqlState err of
      case sessErr of
        Hs.QueryError _ _ cmdErr ->
          case cmdErr of
            Hs.ClientError _ -> BackendEr . T.pack $ show cmdErr
            Hs.ResultError resErr ->
              case resErr of
                Hs.ServerError sqlState message _ _ _ ->
                  case sqlState of
                    "23505" -> ConflictEr ("PostgreSQL uniqueness violation: " <> Te.decodeUtf8 message)
                    "23503" -> ConflictEr ("PostgreSQL foreign-key violation: " <> Te.decodeUtf8 message)
                    "23514" -> ConflictEr ("PostgreSQL check violation: " <> Te.decodeUtf8 message)
        _ -> BackendEr . T.pack $ show sessErr
    _ -> BackendEr topMsg
